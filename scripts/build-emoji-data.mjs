// Regenerates emoji-data.js from iamcal/emoji-data (the source of the Apple emoji images).
// Usage: node scripts/build-emoji-data.mjs
import { writeFileSync } from "node:fs";

const VERSION = "16.0.0";
const res = await fetch(`https://cdn.jsdelivr.net/npm/emoji-datasource@${VERSION}/emoji.json`);
const all = await res.json();

const ORDER = [
  ["Smileys & Emotion", "Smileys"],
  ["People & Body", "People"],
  ["Animals & Nature", "Nature"],
  ["Food & Drink", "Food"],
  ["Activities", "Activities"],
  ["Travel & Places", "Travel"],
  ["Objects", "Objects"],
  ["Symbols", "Symbols"],
  ["Flags", "Flags"],
];

const apple = all.filter((e) => e.has_img_apple).sort((a, b) => a.sort_order - b.sort_order);
const cats = ORDER.map(([full, label]) => {
  const items = apple
    .filter((e) => e.category === full)
    .map((e) => [e.unified.toLowerCase(), [e.name, ...e.short_names].join(" ").toLowerCase().replace(/_/g, " ")]);
  return { name: label, icon: items[0][0], items };
});

// Skin-tone variants: not shown in the picker, but rendered when typed/pasted.
const extra = [];
for (const e of apple) {
  for (const v of Object.values(e.skin_variations || {})) {
    if (v.has_img_apple) extra.push(v.unified.toLowerCase());
  }
}

const out = `// Generated by scripts/build-emoji-data.mjs from emoji-datasource@${VERSION}. Do not edit.\nwindow.HOOK_EMOJI = ${JSON.stringify({ version: VERSION, cats, extra })};\n`;
writeFileSync(new URL("../emoji-data.js", import.meta.url), out);
console.log(`wrote emoji-data.js: ${cats.reduce((n, c) => n + c.items.length, 0)} emoji, ${extra.length} skin variants, ${out.length} bytes`);
